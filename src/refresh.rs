//! `council refresh`: pick today's models for every role from Artificial Analysis data.
//!
//! ELI5: reads the rules in `models/policy.yaml`, looks up today's model scores and costs, and
//! writes the best model for every role into `lock.yaml`.
//!
//! ```text
//! council refresh                                         # live: needs AA_API_KEY
//! council refresh --offline models/snapshot-2026-11-13.json
//! council refresh --check                                 # exit 1 if lock.yaml is stale or missing
//! council refresh --offline <snapshot> --table balanced   # also print a table of the picks
//! ```
//!
//! Data: Artificial Analysis (<https://artificialanalysis.ai>). Attribution is required by their API terms.

use crate::core::{self, fail};
use crate::py::{self, Json};
use crate::val::{items, Get};
use crate::{complain, say};
use anyhow::Result;
use indexmap::IndexMap;
use serde_json::{json, Map, Value};
use std::path::{Path, PathBuf};

const ROLES: [&str; 5] = ["chair", "experts", "red_team", "elders", "verifier"];
const EXPERT_SEATS: usize = 7;
const HEADER: &str = "# GENERATED by `council refresh` from models/policy.yaml (k values and floors are\n\
                      # starting defaults: tune them against your golden set, see reference/model-modes.md).\n\
                      # Do not edit by hand: change policy.yaml (rules, pins, bans) and re-run. Review diffs in a PR.\n";

/// One model as Artificial Analysis reports it. Numbers keep the spelling they arrived in (65 stays
/// 65, not 65.0), so the lock file reads the same whichever tool wrote it.
#[derive(Clone, Debug)]
struct Model {
    name: String,
    creator: String,
    quality: Value,
    cost: Value,
    minutes: Option<f64>,
    open_weights: bool,
    restricted: bool,
    openrouter_id: Value,
}

impl Model {
    fn base(&self) -> String {
        crate::providers::base_name(&self.name)
    }

    fn q(&self) -> f64 {
        self.quality.as_f64().unwrap_or(0.0)
    }

    fn c(&self) -> Option<f64> {
        self.cost.as_f64()
    }

    fn card(&self) -> Value {
        let mut d = json!({"model": self.name, "creator": self.creator, "quality": self.quality, "cost_per_task": self.cost});
        if py::truthy(&self.openrouter_id) {
            d["openrouter_id"] = self.openrouter_id.clone();
        }
        if self.open_weights {
            d["open_weights"] = json!(true);
        }
        d
    }

    /// The model as a snapshot file holds it.
    fn row(&self) -> Value {
        json!({"name": self.name, "creator": self.creator, "quality": self.quality, "cost_per_task": self.cost, "minutes": self.minutes,
               "open_weights": self.open_weights, "restricted": self.restricted, "openrouter_id": self.openrouter_id})
    }
}

// ----------------------------------------------------------------------------- data loading

/// Model data as loaded: the models, and where and when the data was collected.
type Loaded = (Vec<Model>, Map<String, Value>);

fn dig<'a>(obj: &'a Value, path: &[&str]) -> &'a Value {
    path.iter().fold(obj, |node, key| node.at(key))
}

/// The live data, or `None` after saying on standard error why there is none.
fn load_live(policy: &Value, models_dir: &Path) -> Result<Option<Loaded>> {
    let Some(key) = std::env::var("AA_API_KEY").ok().filter(|k| !k.is_empty()) else {
        complain!(
            "Set AA_API_KEY (free key from artificialanalysis.ai) or pass --offline SNAPSHOT.json"
        );
        return Ok(None);
    };
    let base = policy
        .at("data")
        .s("api_url")
        .trim_end_matches('/')
        .to_string();
    let agent: ureq::Agent = ureq::Agent::config_builder()
        .timeout_global(Some(std::time::Duration::from_secs(60)))
        .build()
        .into();
    let mut payload: Option<Value> = None;
    let mut last_err = String::new();
    for url in [base.clone(), format!("{base}/free")] {
        // the free-tier sibling path, per Artificial Analysis's OpenAPI description
        let reply = agent
            .get(&url)
            .header("x-api-key", &key)
            .header("accept", "application/json")
            .call();
        match reply
            .map_err(|e| e.to_string())
            .and_then(|mut r| r.body_mut().read_to_string().map_err(|e| e.to_string()))
        {
            Ok(text) => match serde_json::from_str::<Value>(&text) {
                Ok(value) => {
                    payload = Some(value);
                    break;
                }
                Err(err) => last_err = format!("the reply is not JSON: {err}"),
            },
            Err(err) => last_err = err,
        }
    }
    let Some(payload) = payload else {
        complain!("Artificial Analysis request failed: {last_err}");
        return Ok(None);
    };
    let mut models = Vec::new();
    for row in payload.list("data") {
        let mut cost = dig(
            row,
            &[
                "artificial_analysis_intelligence_index_cost",
                "cost_per_task",
                "total_cost",
            ],
        );
        if cost.is_null() {
            cost = dig(row, &["pricing", "price_1m_blended_3_to_1"]); // still comparable within one refresh
        }
        let secs = dig(row, &["performance_v3", "time_per_task_seconds"])
            .as_f64()
            .filter(|s| *s != 0.0);
        let name = if row.truthy("name") {
            row.show("name")
        } else {
            row.get("slug")
                .map(py::to_str)
                .unwrap_or_else(|| "?".to_string())
        };
        let creator = row
            .at("model_creator")
            .get("name")
            .map(py::to_str)
            .unwrap_or_else(|| "?".to_string());
        models.push(Model {
            name,
            creator,
            quality: dig(
                row,
                &["evaluations", "artificial_analysis_intelligence_index"],
            )
            .clone(),
            cost: cost.clone(),
            minutes: secs.map(|s| s / 60.0),
            open_weights: py::truthy(dig(row, &["licensing", "is_open_weights"])),
            restricted: row.truthy("trusted_access"),
            openrouter_id: row.at("openrouter_api_id").clone(),
        });
    }
    let today = crate::clock::today_iso();
    let mut meta = Map::new();
    meta.insert(
        "source".to_string(),
        json!("Artificial Analysis API (artificialanalysis.ai)"),
    );
    meta.insert("collected".to_string(), json!(today));
    meta.insert("index".to_string(), json!("AA Intelligence Index (live)"));
    let mut snapshot = meta.clone();
    snapshot.insert(
        "models".to_string(),
        Value::Array(models.iter().map(Model::row).collect()),
    );
    core::write_text(
        &models_dir.join(format!("snapshot-{today}.json")),
        &Json::ONE.dumps(&Value::Object(snapshot)),
    )?;
    Ok(Some((models, meta)))
}

/// A snapshot file, or `None` after saying on standard error what is wrong with it.
fn load_offline(path: &Path) -> Option<Loaded> {
    let text = match core::read_text(path) {
        Ok(text) => text,
        Err(err) => {
            complain!("cannot read the snapshot {}: {err}", path.display());
            return None;
        }
    };
    let raw: Value = match serde_json::from_str(&text) {
        Ok(raw) => raw,
        Err(err) => {
            complain!("the snapshot {} is not valid JSON: {err}", path.display());
            return None;
        }
    };
    let Some(rows) = raw.at("models").as_array() else {
        complain!("the snapshot {} has no \"models\" list", path.display());
        return None;
    };
    if !rows
        .iter()
        .all(|r| r.at("name").is_string() && r.at("creator").is_string())
    {
        complain!(
            "the snapshot {} has a model without a name or a creator",
            path.display()
        );
        return None;
    }
    let models = rows
        .iter()
        .map(|r| Model {
            name: r.show("name"),
            creator: r.show("creator"),
            quality: r.at("quality").clone(),
            cost: if r.has("cost_per_task") {
                r.at("cost_per_task").clone()
            } else {
                r.at("cost").clone()
            },
            minutes: r.num("minutes"),
            open_weights: r.truthy("open_weights"),
            restricted: r.truthy("restricted"),
            openrouter_id: r.at("openrouter_id").clone(),
        })
        .collect();
    let meta = ["source", "collected", "index"]
        .iter()
        .map(|k| ((*k).to_string(), raw.at(k).clone()))
        .collect();
    Some((models, meta))
}

// ----------------------------------------------------------------------------- selection

fn usable(models: &[Model], policy: &Value) -> Vec<Model> {
    let bans = crate::val::strings(policy.at("bans"));
    models
        .iter()
        .filter(|m| !m.quality.is_null() && !bans.iter().any(|b| m.name.starts_with(b.as_str())))
        .filter(|m| {
            !m.restricted
                || items(policy.at("access"))
                    .any(|(k, v)| m.name.starts_with(k.as_str()) && v.truthy("has_access"))
        })
        .cloned()
        .collect()
}

fn in_family(models: &[Model], fam: &Value, warnings: &mut Vec<String>, name: &str) -> Vec<Model> {
    if fam.truthy("open_weights_only") {
        return models.iter().filter(|m| m.open_weights).cloned().collect();
    }
    if fam.s("requires") == "openrouter_id" {
        let known: Vec<Model> = models
            .iter()
            .filter(|m| py::truthy(&m.openrouter_id))
            .cloned()
            .collect();
        if !known.is_empty() {
            return known;
        }
        warnings.push(format!(
            "{name}: OpenRouter availability unknown in this snapshot; using all usable models. \
             Run a live refresh to filter by openrouter_api_id."
        ));
        return models.to_vec();
    }
    match fam.get("creators") {
        Some(Value::Array(creators)) => models
            .iter()
            .filter(|m| {
                creators
                    .iter()
                    .any(|c| c.as_str() == Some(m.creator.as_str()))
            })
            .cloned()
            .collect(),
        Some(Value::String(one)) if one != "any" => models
            .iter()
            .filter(|m| one.contains(m.creator.as_str()))
            .cloned()
            .collect(),
        _ => models.to_vec(),
    }
}

/// quality - k * log2(cost): each doubling of cost must buy at least k more index points.
fn score(m: &Model, k: f64) -> Option<f64> {
    let cost = m.c().filter(|c| *c > 0.0)?;
    Some(m.q() - k * cost.log2())
}

/// `score(m, k) or fallback`: a missing score, and a score of exactly zero, count as the fallback.
fn score_or(m: &Model, k: f64, fallback: f64) -> f64 {
    score(m, k).filter(|s| *s != 0.0).unwrap_or(fallback)
}

fn best<'a>(pool: impl IntoIterator<Item = &'a Model>, k: f64, tie: f64) -> Option<&'a Model> {
    let scored: Vec<(f64, &Model)> = pool
        .into_iter()
        .filter_map(|m| score(m, k).map(|s| (s, m)))
        .collect();
    let top = scored
        .iter()
        .map(|(s, _)| *s)
        .fold(f64::NEG_INFINITY, f64::max);
    let mut tied: Vec<&Model> = scored
        .iter()
        .filter(|(s, _)| top - s <= tie)
        .map(|(_, m)| *m)
        .collect();
    // within a tie the faster model wins, then the better one
    tied.sort_by(|a, b| {
        let key = |m: &Model| (m.minutes.unwrap_or(1e9), -m.q());
        key(a)
            .partial_cmp(&key(b))
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    tied.first().copied()
}

/// The picks for one family (or for the cross-lab mix) under one profile.
struct Picks {
    chair: Model,
    experts: Vec<Model>,
    red_team: Model,
    elders: Vec<Model>,
    verifier: Model,
}

fn k_of(rule: &Value) -> f64 {
    rule.num("k").unwrap_or(0.0)
}

fn pick_config(
    cands: &[Model],
    all_usable: &[Model],
    prof: &Value,
    policy: &Value,
    crosslab: bool,
) -> Result<Picks, String> {
    let tie = policy.at("tie_break").num("within_points").unwrap_or(0.0);
    let top_quality = |pool: &[Model]| pool.iter().map(Model::q).fold(f64::NEG_INFINITY, f64::max);
    let labs = crate::val::strings(policy.at("crosslab_labs"));

    // chair
    let c = prof.at("chair");
    let chair = match c.num("floor_vs_best") {
        Some(floor) => {
            let top_q = top_quality(cands);
            best(
                cands.iter().filter(|m| m.q() >= floor * top_q),
                k_of(c),
                tie,
            )
        }
        None => best(cands, k_of(c), tie),
    };
    let Some(chair) = chair.cloned() else {
        return Err("no model with cost data in this family".to_string());
    };

    // experts: one primary workhorse + diversity seats
    let e = prof.at("experts");
    let ek = k_of(e);
    let pool: Vec<&Model> = cands
        .iter()
        .filter(|m| m.q() >= e.num("floor").unwrap_or(0.0) * chair.q())
        .collect();
    let primary = best(pool.iter().copied(), ek, tie)
        .cloned()
        .unwrap_or_else(|| chair.clone());
    let mut creators: Vec<&str> = pool.iter().map(|m| m.creator.as_str()).collect();
    creators.sort_unstable();
    creators.dedup();
    let by_creator = creators.len() > 1;
    let group = |m: &Model| {
        if by_creator {
            m.creator.clone()
        } else {
            m.base()
        }
    };
    let mut seats: Vec<Model> = Vec::new();
    if crosslab {
        // cross-lab mode exists for decorrelated errors: one seat per other lab that clears the
        // quality floor, even if it is pricier than the workhorse (no score margin).
        for lab in labs.iter().filter(|lab| **lab != primary.creator) {
            if let Some(pick) = best(pool.iter().copied().filter(|m| m.creator == *lab), ek, tie) {
                seats.push(pick.clone());
            }
        }
    } else {
        let mut groups: Vec<String> = pool
            .iter()
            .map(|m| group(m))
            .filter(|g| *g != group(&primary))
            .collect();
        groups.sort();
        groups.dedup();
        // a seat must score within `diversity_margin` points of the main workhorse
        let floor_s = score_or(&primary, ek, 0.0) - e.num("diversity_margin").unwrap_or(12.0);
        for g in groups {
            if let Some(pick) = best(
                pool.iter()
                    .copied()
                    .filter(|m| group(m) == g && score_or(m, ek, -1e9) >= floor_s),
                ek,
                tie,
            ) {
                seats.push(pick.clone());
            }
        }
        seats.sort_by(|a, b| {
            score_or(b, ek, -1e9)
                .partial_cmp(&score_or(a, ek, -1e9))
                .unwrap_or(std::cmp::Ordering::Equal)
        });
        seats.truncate(e.int("diversity_seats").unwrap_or(0).max(0) as usize);
    }
    let mut experts = vec![primary; EXPERT_SEATS.saturating_sub(seats.len())];
    experts.extend(seats);

    // red team: another family when possible, else another model
    let r = prof.at("red_team");
    let floor_q = r.num("floor").unwrap_or(0.0) * chair.q();
    let chair_base = chair.base();
    let mut tiers: Vec<Vec<&Model>> = Vec::new();
    if r.truthy("other_family") {
        tiers.push(
            cands
                .iter()
                .filter(|m| m.creator != chair.creator)
                .collect(),
        );
    }
    tiers.push(cands.iter().filter(|m| m.base() != chair_base).collect());
    tiers.push(cands.iter().filter(|m| m.base() == chair_base).collect());
    // other lab > other model > same model in a fresh context
    let red_team = tiers
        .iter()
        .find_map(|pool| {
            best(
                pool.iter().copied().filter(|m| m.q() >= floor_q),
                k_of(r),
                tie,
            )
        })
        .cloned()
        .unwrap_or_else(|| chair.clone());

    // elders
    let el = prof.at("elders");
    let (elk, el_floor) = (k_of(el), el.num("floor").unwrap_or(0.0));
    let mut elders: Vec<Model> = Vec::new();
    if crosslab {
        for lab in &labs {
            let lab_pool: Vec<Model> = all_usable
                .iter()
                .filter(|m| m.creator == *lab)
                .cloned()
                .collect();
            if lab_pool.is_empty() {
                continue;
            }
            let top_q = top_quality(&lab_pool);
            if let Some(pick) = best(
                lab_pool.iter().filter(|m| m.q() >= el_floor * top_q),
                elk,
                tie,
            ) {
                elders.push(pick.clone());
            }
        }
    } else {
        let top_q = top_quality(cands);
        let mut per_base: IndexMap<String, &Model> = IndexMap::new();
        for m in cands.iter().filter(|m| m.q() >= el_floor * top_q) {
            let Some(s) = score(m, elk) else { continue };
            let better = per_base
                .get(&m.base())
                .is_none_or(|held| score(held, elk).is_none_or(|held_score| s > held_score));
            if better {
                per_base.insert(m.base(), m);
            }
        }
        let mut ranked: Vec<&Model> = per_base.values().copied().collect();
        ranked.sort_by(|a, b| {
            score(b, elk)
                .partial_cmp(&score(a, elk))
                .unwrap_or(std::cmp::Ordering::Equal)
        });
        elders = ranked.into_iter().take(3).cloned().collect();
        while !elders.is_empty() && elders.len() < 3 {
            elders.push(elders[0].clone()); // fresh contexts of the best model
        }
    }

    // verifier: fast and good enough
    let v = prof.at("verifier");
    let (vk, min_q, max_minutes) = (
        k_of(v),
        v.num("min_quality").unwrap_or(0.0),
        v.num("max_minutes").unwrap_or(f64::INFINITY),
    );
    let verifier = best(
        cands
            .iter()
            .filter(|m| m.minutes.is_some_and(|t| t <= max_minutes) && m.q() >= min_q),
        vk,
        tie,
    )
    .or_else(|| best(cands.iter().filter(|m| m.q() >= min_q), vk, tie))
    .cloned()
    .unwrap_or_else(|| chair.clone());
    Ok(Picks {
        chair,
        experts,
        red_team,
        elders,
        verifier,
    })
}

fn relative_cost(cfg: &Picks, cm: &Value) -> Option<f64> {
    let cost = |m: &Model| m.c();
    let mean = |xs: &[Model]| -> Option<f64> {
        let mut sum = 0.0;
        for x in xs {
            sum += cost(x)?;
        }
        (!xs.is_empty()).then(|| sum / xs.len() as f64)
    };
    let n = |key: &str| cm.num(key).unwrap_or(0.0);
    let per_loop = EXPERT_SEATS as f64 * n("expert_passes_per_loop") * mean(&cfg.experts)?
        + n("red_team_passes_per_loop") * cost(&cfg.red_team)?
        + cfg.elders.len() as f64 * n("elder_passes_per_loop") * mean(&cfg.elders)?
        + n("chair_passes_per_loop") * cost(&cfg.chair)?;
    Some(n("loops") * per_loop + n("final_chair_passes") * cost(&cfg.chair)?)
}

/// Every profile's picks for every mode, as the lock file holds them, with the warnings raised on the way.
fn resolve(models: &[Model], policy: &Value) -> Result<(Value, Vec<String>)> {
    let mut warnings: Vec<String> = Vec::new();
    let ok = usable(models, policy);
    if ok.is_empty() {
        return fail("no usable model in the data: every model is banned, restricted or has no quality score");
    }
    let mut picked: IndexMap<String, IndexMap<String, Result<Picks, String>>> = IndexMap::new();
    for (pname, prof) in items(policy.at("profiles")) {
        let mut modes = IndexMap::new();
        for (fname, fam) in items(policy.at("families")) {
            let cands = in_family(&ok, fam, &mut warnings, &format!("fanout:{fname}"));
            let picks = if cands.is_empty() {
                Err("no usable models".to_string())
            } else {
                pick_config(&cands, &ok, prof, policy, false)
            };
            modes.insert(format!("fanout:{fname}"), picks);
        }
        let mix = in_family(
            &ok,
            policy.at("families").at("mix"),
            &mut warnings,
            "crosslab",
        );
        modes.insert(
            "crosslab".to_string(),
            pick_config(&mix, &ok, prof, policy, true),
        );
        picked.insert(pname.clone(), modes);
    }
    // relative cost, normalised so that balanced / crosslab = 1.00
    let cm = policy.at("cost_model");
    let reference = picked
        .get("balanced")
        .and_then(|modes| modes.get("crosslab"))
        .and_then(|p| p.as_ref().ok())
        .and_then(|p| relative_cost(p, cm));
    let Some(reference) = reference.filter(|r| *r != 0.0) else {
        return fail("the balanced cross-lab council could not be priced: the policy needs a `balanced` profile and models with cost data");
    };
    let mut configs = Map::new();
    for (pname, modes) in &picked {
        let mut out = Map::new();
        for (key, picks) in modes {
            let cfg = match picks {
                Err(error) => json!({"error": error}),
                Ok(p) => {
                    let cards = |ms: &[Model]| Value::Array(ms.iter().map(Model::card).collect());
                    let Some(cost) = relative_cost(p, cm) else {
                        return fail(format!("{pname}/{key}: a picked model has no cost"));
                    };
                    json!({"chair": p.chair.card(), "experts": cards(&p.experts), "red_team": p.red_team.card(), "elders": cards(&p.elders),
                           "verifier": p.verifier.card(), "relative_cost": py::round(cost / reference, 2)})
                }
            };
            out.insert(key.clone(), cfg);
        }
        configs.insert(pname.clone(), Value::Object(out));
    }
    for (pname, efforts) in items(policy.at("solo_efforts")) {
        let solo: Map<String, Value> = items(efforts)
            .map(|(role, effort)| {
                (
                    role.clone(),
                    json!(format!("current model @ {}", py::to_str(effort))),
                )
            })
            .collect();
        if !configs.contains_key(pname) {
            configs.insert(pname.clone(), json!({}));
        }
        configs[pname.as_str()]["solo"] = Value::Object(solo);
    }
    warnings.sort();
    warnings.dedup();
    Ok((Value::Object(configs), warnings))
}

// ----------------------------------------------------------------------------- output

/// Every pick of a lock file on one line each: `profile/mode/role` -> model name(s).
fn flat_picks(lock: &Value) -> IndexMap<String, String> {
    let mut flat = IndexMap::new();
    for (p, fams) in items(lock.at("configs")) {
        for (f, cfg) in items(fams) {
            for role in ROLES {
                let picked = match cfg.at(role) {
                    Value::Array(list) => {
                        let mut names: Vec<String> = list.iter().map(|x| x.show("model")).collect();
                        names.sort();
                        names.dedup();
                        names.join(", ")
                    }
                    obj @ Value::Object(_) => obj.show("model"),
                    Value::String(text) => text.clone(),
                    _ => continue,
                };
                flat.insert(format!("{p}/{f}/{role}"), picked);
            }
        }
    }
    flat
}

/// Pins from the policy: `profile/mode/role[/lab]` -> a model name that must sit there.
fn apply_pins(lock: &mut Value, pins: &Value, models: &[Model]) {
    for (path, name) in items(pins) {
        let name = py::to_str(name);
        let parts: Vec<&str> = path.split('/').collect();
        let card = models
            .iter()
            .rev()
            .find(|m| m.name == name)
            .map(Model::card);
        let cfg = match parts.as_slice() {
            [p, f, _, ..] => lock["configs"]
                .get_mut(*p)
                .and_then(|fams| fams.get_mut(*f))
                .filter(|cfg| cfg.is_object()),
            _ => None,
        };
        let (Some(cfg), Some(card)) = (cfg, card) else {
            complain!("warning: pin {path} -> {name} not applied");
            continue;
        };
        let (role, rest) = (parts[2], parts.get(3).copied());
        let seats = cfg
            .at(role)
            .as_array()
            .cloned()
            .filter(|_| matches!(role, "experts" | "elders"));
        cfg[role] = match (seats, rest) {
            // e.g. .../elders/Google: only that lab's seats change
            (Some(seats), Some(lab)) => seats
                .into_iter()
                .map(|x| {
                    if x.s("creator") == lab || x.s("model").starts_with(lab) {
                        card.clone()
                    } else {
                        x
                    }
                })
                .collect(),
            (Some(seats), None) => Value::Array(vec![card; seats.len()]),
            _ => card,
        };
    }
}

fn markdown_table(lock: &Value, profile: &str) -> String {
    let mut rows = vec![
        "| Mode | Chair | Experts (7 seats) | Red team | Elders | Rel. cost |".to_string(),
        "| --- | --- | --- | --- | --- | --- |".to_string(),
    ];
    for (key, cfg) in items(lock.at("configs").at(profile)) {
        if cfg.has("error") {
            rows.push(format!("| {key} | {} | | | | |", cfg.show("error")));
        } else if key == "solo" {
            rows.push(format!(
                "| solo | {} | {} | {} | {} | n/a |",
                cfg.show("chair"),
                cfg.show("experts"),
                cfg.show("red_team"),
                cfg.show("elders")
            ));
        } else {
            let mut counts: IndexMap<String, usize> = IndexMap::new();
            for x in cfg.list("experts") {
                *counts.entry(x.show("model")).or_insert(0) += 1;
            }
            let experts: Vec<String> = counts.iter().map(|(m, n)| format!("{n}x {m}")).collect();
            let elders: Vec<String> = cfg.list("elders").iter().map(|x| x.show("model")).collect();
            rows.push(format!(
                "| {key} | {} | {} | {} | {} | {} |",
                cfg.at("chair").show("model"),
                experts.join(" + "),
                cfg.at("red_team").show("model"),
                elders.join(", "),
                cfg.show("relative_cost")
            ));
        }
    }
    rows.join("\n")
}

/// `council refresh`. Returns the exit code: 1 when `--check` finds the model data missing or stale.
pub fn run(
    offline: Option<&str>,
    check: bool,
    table: Option<&str>,
    out: Option<&str>,
) -> Result<i32> {
    let models_dir = crate::assets::models_dir();
    let out_path: PathBuf = out
        .map(PathBuf::from)
        .unwrap_or_else(|| models_dir.join("lock.yaml"));
    let policy = core::policy();
    if !policy.is_object() {
        return fail("models/policy.yaml is missing or is not a mapping");
    }
    let read_lock = |path: &Path| -> Result<Value> {
        crate::yaml::load(&core::read_text(path)?)
            .map_err(|e| anyhow::anyhow!("{}: {e}", path.display()))
    };
    if check {
        if !out_path.exists() {
            say!("lock.yaml missing: run `council refresh`");
            return Ok(1);
        }
        let lock = read_lock(&out_path)?;
        let collected = lock.at("data").show("collected");
        let Some(date) = crate::clock::parse_date(&collected) else {
            return fail(format!(
                "{}: data.collected is not a date ({})",
                out_path.display(),
                py::str_repr(&collected)
            ));
        };
        let age = (crate::clock::today() - date).num_days();
        let limit = policy.at("data").show("stale_after_days");
        say!("model data is {age} days old (limit {limit})");
        return Ok(i32::from(
            policy
                .at("data")
                .num("stale_after_days")
                .is_some_and(|l| age as f64 > l),
        ));
    }
    let loaded = match offline {
        Some(path) => load_offline(Path::new(path)),
        None => load_live(&policy, &models_dir)?,
    };
    let Some((models, meta)) = loaded else {
        return Ok(1);
    };
    let (configs, warnings) = resolve(&models, &policy)?;
    let mut data = meta;
    data.insert(
        "attribution".to_string(),
        json!("Model data: Artificial Analysis (https://artificialanalysis.ai)"),
    );
    let mut lock = json!({"generated": crate::clock::today_iso(), "data": data, "policy_version": policy.at("version"), "warnings": warnings,
                          "configs": configs});
    apply_pins(&mut lock, policy.at("pins"), &models);

    let old = if out_path.exists() {
        flat_picks(&read_lock(&out_path)?)
    } else {
        IndexMap::new()
    };
    let new = flat_picks(&lock);
    let mut keys: Vec<&String> = new.keys().collect();
    keys.sort();
    let changes: Vec<String> = keys
        .into_iter()
        .filter(|k| old.get(*k) != new.get(*k))
        .map(|k| {
            format!(
                "  {k}: {} -> {}",
                old.get(k).map(String::as_str).unwrap_or("(none)"),
                new[k]
            )
        })
        .collect();
    core::write_text(
        &out_path,
        &format!("{HEADER}{}", crate::yaml::dump_width(&lock, 120)),
    )?;
    say!(
        "wrote {} ({} picks, {} changed)",
        out_path.display(),
        new.len(),
        changes.len()
    );
    if !old.is_empty() && !changes.is_empty() {
        say!("changes since last lock:\n{}", changes.join("\n"));
    }
    for w in &warnings {
        say!("warning: {w}");
    }
    if let Some(profile) = table {
        say!("{}", markdown_table(&lock, profile));
    }
    Ok(0)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn model(name: &str, creator: &str, quality: f64, cost: f64, minutes: f64) -> Model {
        Model {
            name: name.to_string(),
            creator: creator.to_string(),
            quality: json!(quality),
            cost: json!(cost),
            minutes: Some(minutes),
            open_weights: false,
            restricted: false,
            openrouter_id: Value::Null,
        }
    }

    #[test]
    fn cost_only_matters_as_much_as_the_profile_says() {
        let (strong, cheap) = (
            model("Strong (max)", "A", 70.0, 32.0, 40.0),
            model("Cheap (low)", "B", 60.0, 1.0, 5.0),
        );
        let pool = [strong.clone(), cheap.clone()];
        assert_eq!(
            best(&pool, 0.0, 0.5).map(|m| m.name.as_str()),
            Some("Strong (max)")
        ); // k = 0: ignore cost
        assert_eq!(
            best(&pool, 6.0, 0.5).map(|m| m.name.as_str()),
            Some("Cheap (low)")
        ); // 70 - 6 * 5 = 40 < 60
        assert_eq!(score(&model("Free", "C", 50.0, 0.0, 1.0), 2.0), None);
        // within a tie the faster model wins
        let (slow, fast) = (
            model("Slow", "A", 60.0, 1.0, 30.0),
            model("Fast", "B", 59.8, 1.0, 3.0),
        );
        assert_eq!(
            best(&[slow, fast], 2.0, 0.5).map(|m| m.name.as_str()),
            Some("Fast")
        );
    }

    #[test]
    fn banned_and_restricted_models_are_left_out() {
        let mut locked = model("Mythos 5.2", "A", 80.0, 50.0, 60.0);
        locked.restricted = true;
        let models = [
            locked,
            model("Banned 1", "B", 70.0, 5.0, 5.0),
            model("Fine", "C", 60.0, 5.0, 5.0),
        ];
        let names = |policy: Value| {
            usable(&models, &policy)
                .iter()
                .map(|m| m.name.clone())
                .collect::<Vec<_>>()
        };
        assert_eq!(names(json!({"bans": ["Banned"]})), ["Fine"]);
        assert_eq!(
            names(json!({"access": {"Mythos": {"has_access": true}}})),
            ["Mythos 5.2", "Banned 1", "Fine"]
        );
    }

    #[test]
    fn picks_are_listed_one_per_role() {
        let lock = json!({"configs": {"max": {"crosslab": {"chair": {"model": "A"}, "experts": [{"model": "B"}, {"model": "A"}, {"model": "B"}]},
                                              "solo": {"chair": "current model @ max"}, "fanout:x": {"error": "no usable models"}}}});
        let flat = flat_picks(&lock);
        assert_eq!(flat["max/crosslab/experts"], "A, B");
        assert_eq!(flat["max/solo/chair"], "current model @ max");
        assert_eq!(flat.len(), 3);
    }
}
